"""Bring the app's Extra Buttons patches and their address tables up to date with the site's.

    python gen_builds.py

Copies ../web/extra-buttons-*.ips into romfs/ (which the app carries inside it) and writes
source/builds.h from the .json next to each (made by tools/gen_extra_buttons.py), so the app and
the site always carry the same patches. Run it before `make`; romfs/ is not kept in git.
"""
import glob, json, os, shutil, sys

HERE = os.path.dirname(os.path.abspath(__file__))
# merge.h's SYM_ order = the order the randomizer writes a seed's records.
ORDER = ['rItemOverrides', 'rEntranceOverrides', 'gSettingsContext', 'gSpoilerData', 'gSpoilerDataLocs',
         'rScrubRandomItemPrices', 'rShopsanityPrices', 'rDungeonRewardOverrides', 'rCustomMessages',
         'ptrCustomMessageEntries', 'numCustomMessageEntries', 'rBGMOverrides', 'rSfxData',
         'rDungeonInfoData', 'rDungeonImportance', 'rGsLocOverrides', 'rEnemyOverrides']
REGIONS = {'usa': 'MERGE_REGION_USA', 'eur': 'MERGE_REGION_EUR'}


def main(importer):
    web = os.path.join(importer, 'web')
    sys.path.insert(0, os.path.join(importer, 'tools'))
    import seedmerge
    assert seedmerge.ORDER == ORDER, 'the importer writes symbols in another order: update merge.h and ORDER'
    os.makedirs(os.path.join(HERE, 'romfs'), exist_ok=True)
    for old in glob.glob(os.path.join(HERE, 'romfs', 'extra-buttons-*.ips')):
        os.remove(old)
    rows = []
    for build in seedmerge.BUILDS:
        for region in seedmerge.REGIONS:
            name = 'extra-buttons-%s-%s' % (build, region)
            info = json.load(open(os.path.join(web, name + '.json'), encoding='utf-8'))
            shutil.copyfile(os.path.join(web, name + '.ips'), os.path.join(HERE, 'romfs', name + '.ips'))
            syms = ', '.join('{ 0x%06X, %d }' % tuple(info['symbols'].get(s, (0, 0))) for s in ORDER)
            rows.append('    { "%s", "romfs:/%s.ips", %s, 0x%X, %d, %d, %d,\n      { %s } },' % (
                info['source'], name, REGIONS[region], info['randoStart'], info['addedBytes'],
                info['settings']['region'], info['settings']['customTunicColors'], syms))
    text = ('// Generated by gen_builds.py from ../web/extra-buttons-*.json. Do not edit.\n'
            '#pragma once\n\n#include "merge.h"\n\n'
            'static const MergeBuild gBuilds[] = {\n' + '\n'.join(rows) + '\n};\n'
            '#define BUILD_COUNT ((int)(sizeof(gBuilds) / sizeof(gBuilds[0])))\n')
    open(os.path.join(HERE, 'source', 'builds.h'), 'w', encoding='utf-8', newline='\n').write(text)
    print('wrote builds.h with', len(rows), 'patches')


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..'))
